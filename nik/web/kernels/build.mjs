// Assemble qgemm.wat -> qgemm.wasm and an inlined base64 module (kernels.js).
//   cd nik/web/kernels && npm i wabt@1.0.39 && node build.mjs
import fs from 'fs';
import wabtInit from 'wabt';
const wabt = await wabtInit();
const here = new URL('.', import.meta.url).pathname;
const mod = wabt.parseWat('qgemm.wat', fs.readFileSync(here + 'qgemm.wat', 'utf8'), { simd: true });
mod.validate();
const { buffer } = mod.toBinary({});
fs.writeFileSync(here + 'qgemm.wasm', buffer);
fs.writeFileSync(here + 'kernels.js', `// generated by build.mjs from qgemm.wat — do not edit\nexport const QGEMM_WASM = '${Buffer.from(buffer).toString('base64')}';\n`);
console.log('qgemm.wasm', buffer.length, 'bytes');
